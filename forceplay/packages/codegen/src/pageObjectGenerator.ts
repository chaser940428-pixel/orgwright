import { SObjectDescribe } from '@kplay/core';

export interface PomGeneratorOptions {
  className?: string;
  basePageImportPath?: string;
  lightningHelpersImportPath?: string;
  includeFieldHelpers?: boolean;
}

function toPascalCase(str: string): string {
  const cleaned = str.replace(/__c$/i, '');
  return cleaned
    .replace(/[^a-zA-Z0-9]+(.)/g, (_, chr) => chr.toUpperCase())
    .replace(/^[^a-zA-Z0-9]+/, '')
    .replace(/^[a-z]/, c => c.toUpperCase());
}

function toCamelCase(str: string): string {
  const pascal = toPascalCase(str);
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

/**
 * Generates a clean, modular, production-ready Playwright Page Object class extending BasePage
 * for any Salesforce standard or custom SObject (e.g. Property__c, Account, Account, Opportunity).
 */
export function generatePageObject(
  describe: SObjectDescribe,
  options: PomGeneratorOptions = {}
): string {
  const rawName = describe.label || describe.apiName;
  const baseName = toPascalCase(rawName);
  const className = options.className || `${baseName}Page`;
  const basePagePath = options.basePageImportPath || './BasePage';
  const lightningHelpersPath = options.lightningHelpersImportPath || '../utils/lightning-helpers';

  const fields = Object.values(describe.fields || {});
  const actions = describe.actions || [];
  const tabs = describe.tabs || [];

  // Locators declarations
  const locatorDeclarations: string[] = [];
  const locatorInitializations: string[] = [];

  for (const field of fields.slice(0, 15)) {
    const propName = `${toCamelCase(field.label || field.apiName)}Input`;
    const label = field.label || field.apiName;
    locatorDeclarations.push(`  readonly ${propName}: Locator;`);
    locatorInitializations.push(
      `    this.${propName} = page.locator('records-record-layout-item:has-text("${label}"), lightning-input:has-text("${label}"), lightning-combobox:has-text("${label}")').first();`
    );
  }

  // Standard action buttons
  locatorDeclarations.push(`  readonly saveButton: Locator;`);
  locatorDeclarations.push(`  readonly cancelButton: Locator;`);
  locatorInitializations.push(`    this.saveButton = page.getByRole('button', { name: /Save|Done/i }).first();`);
  locatorInitializations.push(`    this.cancelButton = page.getByRole('button', { name: /Cancel|Close/i }).first();`);

  // Action methods
  const actionMethodDeclarations: string[] = [];
  for (const act of actions) {
    const methodName = `click${toPascalCase(act.label || act.name)}`;
    const actionLabel = act.label || act.name;
    actionMethodDeclarations.push(`
  /**
   * Triggers the "${actionLabel}" action.
   */
  async ${methodName}(): Promise<void> {
    await LightningHelpers.clickButton(this.page, /${actionLabel}/i);
    await LightningHelpers.waitForLightningReady(this.page);
  }`);
  }

  const code = `import { Page, Locator, expect } from '@playwright/test';
import { BasePage } from '${basePagePath}';
import { LightningHelpers } from '${lightningHelpersPath}';

/**
 * Page Object for ${describe.label} (${describe.apiName}).
 * Auto-generated by KPlay Studio Codegen.
 */
export class ${className} extends BasePage {
  readonly objectApiName = '${describe.apiName}';
  readonly listUrl = '${describe.listUrl || `/lightning/o/${describe.apiName}/list`}';

  // Locators
${locatorDeclarations.join('\n')}

  constructor(page: Page) {
    super(page);
${locatorInitializations.join('\n')}
  }

  /**
   * Opens the object list view.
   */
  async navigateToList(filterName = 'Recent'): Promise<void> {
    await this.navigateToObjectList(this.objectApiName, filterName);
    await LightningHelpers.waitForLightningReady(this.page);
  }

  /**
   * Opens a record by 15/18-character ID or clicks the first matching row in the list view.
   */
  async openRecord(recordIdOrFilter = 'Recent'): Promise<void> {
    if (recordIdOrFilter.startsWith('00') || recordIdOrFilter.startsWith('a0') || recordIdOrFilter.startsWith('a2')) {
      await this.navigateToRecord(recordIdOrFilter);
    } else {
      await this.navigateToList(recordIdOrFilter);
      const recordRow = this.page.locator('tbody tr th a, tbody tr td a[data-refid="recordId"], tbody tr a').first();
      await recordRow.waitFor({ state: 'visible', timeout: 20000 });
      await recordRow.click();
      await LightningHelpers.waitForLightningReady(this.page);
    }
  }

  /**
   * Activates a record tab by visible label (e.g. Details, Related, Notes).
   */
  async selectTab(tabLabel: string): Promise<void> {
    const tab = this.page.getByRole('tab', { name: new RegExp(tabLabel, 'i') }).first();
    await tab.waitFor({ state: 'visible', timeout: 10000 });
    await tab.click();
    await LightningHelpers.waitForLightningReady(this.page);
  }

  /**
   * Reads a field value from the record layout.
   */
  async getFieldValue(fieldLabel: string): Promise<string> {
    // Ensure Details tab is open if available
    const detailsTab = this.page.getByRole('tab', { name: /Details/i }).first();
    if (await detailsTab.isVisible({ timeout: 4000 })) {
      await detailsTab.click();
      await LightningHelpers.waitForLightningReady(this.page);
    }

    const fieldContainer = this.page.locator(\`records-record-layout-item:has-text("\${fieldLabel}"), records-record-layout-row:has-text("\${fieldLabel}")\`).first();
    if (await fieldContainer.isVisible({ timeout: 8000 })) {
      return (await fieldContainer.innerText()).trim();
    }
    return '';
  }

  /**
   * Sets the value of a text or picklist field on the record.
   */
  async setFieldValue(fieldLabel: string, value: string): Promise<void> {
    const container = this.page.locator(\`records-record-layout-item:has-text("\${fieldLabel}"), lightning-input:has-text("\${fieldLabel}"), lightning-combobox:has-text("\${fieldLabel}")\`).first();
    
    // Check if combobox
    const combobox = container.locator('lightning-base-combobox, input[role="combobox"]').first();
    if (await combobox.isVisible({ timeout: 3000 })) {
      await LightningHelpers.selectCombobox(this.page, container, value);
    } else {
      await LightningHelpers.fillLightningInput(this.page, container, value);
    }
  }

  /**
   * Clicks an action button or quick action.
   */
  async clickAction(actionLabel: string): Promise<void> {
    await LightningHelpers.clickButton(this.page, new RegExp(actionLabel, 'i'));
    await LightningHelpers.waitForLightningReady(this.page);
  }
${actionMethodDeclarations.join('\n')}
}
`;

  return code;
}
